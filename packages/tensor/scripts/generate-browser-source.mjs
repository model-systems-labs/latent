import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const runtimePath = resolve(packageRoot, "src/runtime.ts");
const generatedPath = resolve(packageRoot, "src/generated/browser-source.ts");
const source = await readFile(runtimePath, "utf8");

const result = ts.transpileModule(source, {
  fileName: runtimePath,
  reportDiagnostics: true,
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
    removeComments: false,
    sourceMap: false,
  },
});

const errors = (result.diagnostics ?? []).filter(
  (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
);
assert.equal(
  errors.length,
  0,
  errors.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")).join("\n"),
);

const generated = [
  "// Generated by scripts/generate-browser-source.mjs from src/runtime.ts.",
  "// Do not edit this file directly.",
  `export const LATENT_TENSOR_SOURCE: string = ${JSON.stringify(result.outputText)};`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(generatedPath, "utf8").catch(() => "");
  assert.equal(current, generated, "browser source is stale; run npm run generate:browser-source");
} else {
  await mkdir(dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, generated, "utf8");
}
